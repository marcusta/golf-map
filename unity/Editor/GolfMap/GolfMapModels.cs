// The course's model library (models.json beside palette.json, golfmap-models-v1; CONTEXT.md "Model
// library"): every model the course can draw - trees, and the zone palettes' grass, ground plants and
// bushes - where it is drawn, its size and its look. The palette refers to it by model id
// ('arborist:<Arborist catalogue label>', 'vsp:<Unity prefab>' or 'vsp:texture:<texture>', optionally
// '#<variant>'); GolfMapPalette.Load resolves those references through it, as
// shared/vegetation/tree-models.ts does for the matcher in node, and GolfMapGrass.Load the zone items'.
// This copy (and palette.json beside it) is generated by the repo's `bun run models -- sync`: models.json is
// the course's resolved library (the shared docs/gspro/model-library.json with the course's overrides and
// own models, docs/gspro/<course>/models.json, over it), palette.json the repo's byte for byte. Nothing in
// Unity writes either file itself: the Palette panel's Add Arborist model and Save run the repo's
// `bun run models -- add / palette` (RunCli below), which write the repo's files and sync them here.
//
// Only a vsp model is a prefab of this project (its "unity" node: guid, path, assetType, catalogueGuid,
// originalPath). An Arborist model has no prefab here: the planter writes its trees as placements for
// the Arborist writer (pipeline/arborist.py trees) and keeps them out of the course's VSP.
//
// The model id is parsed and built only here in C# (Parse, Id); the twins are shared/vegetation/model-id.ts
// and pipeline/arborist.py model_id/parse_model_id, and shared/vegetation/model-ids.fixture.json holds the good
// and bad ids all three agree on (an empty '#' variant is no id). A model's renderer is its id's: a library entry whose
// "renderer" says otherwise is refused. The rules for a new model (kinds, forms, catalogue sizes) live only
// in shared/vegetation/tree-models.ts addArboristModel.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;

namespace GolfMap.Editor
{
    public static class GolfMapModels
    {
        public const string Format = "golfmap-models-v1";
        public const string FileName = "models.json";
        // What draws a model in GSPro.
        public const string Arborist = "arborist", Vsp = "vsp";

        public static string PathBeside(string palettePath) { return Path.Combine(Path.GetDirectoryName(palettePath) ?? "", FileName).Replace('\\', '/'); }

        // ('vsp', 'PF_Oak_tall Terrain') -> 'vsp:PF_Oak_tall Terrain'; with a variant 'arborist:X#dark'; a texture 'vsp:texture:<stem>'.
        public static string Id(string renderer, string label, string variant = null, bool texture = false)
        {
            return renderer + ":" + (texture ? TexturePrefix : "") + label + (string.IsNullOrEmpty(variant) ? "" : "#" + variant);
        }

        // A vsp texture grass of the zone palettes: 'vsp:texture:<texture file stem>'.
        public const string TexturePrefix = "texture:";

        // 'arborist:S7_American_Elm' -> arborist, S7_American_Elm; false for an id of any other shape. The label is
        // what the renderer calls the model: the part before '#<variant>' (several looks of one asset,
        // 'vsp:texture:Rustic Grass_15#blond'), without 'texture:' for a texture grass.
        public static bool TryParse(string id, out string renderer, out string label)
        {
            int colon = id == null ? -1 : id.IndexOf(':');
            renderer = colon > 0 ? id.Substring(0, colon) : null;
            label = colon > 0 ? id.Substring(colon + 1) : null;
            if (label != null)
            {
                int hash = label.IndexOf('#');
                if (hash >= 0) label = hash == label.Length - 1 ? "" : label.Substring(0, hash);
                if (renderer == Vsp && label.StartsWith(TexturePrefix, StringComparison.Ordinal)) label = label.Substring(TexturePrefix.Length);
            }
            if ((renderer == Arborist || renderer == Vsp) && label.Trim().Length > 0) return true;
            renderer = label = null;
            return false;
        }

        public static void Parse(string id, out string renderer, out string label)
        {
            if (!TryParse(id, out renderer, out label)) throw new Exception("Invalid model id '" + id + "': expected arborist:<catalogue label>, vsp:<Unity prefab> or vsp:texture:<texture>, optionally with #<variant>.");
        }

        public static string Label(string id) { string renderer, label; Parse(id, out renderer, out label); return label; }

        // id -> model node; empty when the course has no library yet.
        public static Dictionary<string, GolfMapJsonObject> Load(string path)
        {
            var result = new Dictionary<string, GolfMapJsonObject>();
            if (!File.Exists(path)) return result;
            var doc = GolfMapJsonDoc.ParseObject(File.ReadAllText(path));
            var models = doc.Array("models");
            if (doc.String("format") != Format || models == null) throw new Exception("Invalid model library " + path + ": format must be " + Format + ".");
            foreach (var entry in models)
            {
                var o = entry as GolfMapJsonObject;
                var id = o == null ? null : o.String("id");
                if (string.IsNullOrEmpty(id)) throw new Exception("A model without an id in " + path + ".");
                if (result.ContainsKey(id)) throw new Exception("Model " + id + " is in " + path + " twice.");
                string renderer, label; Parse(id, out renderer, out label);
                var said = o.String("renderer");
                if (said != null && said != renderer) throw new Exception("Model " + id + " in " + path + " says renderer '" + said + "', but its id is " + renderer + "'s.");
                result[id] = o;
            }
            return result;
        }

        // A library model as the matcher's asset (enabled and share come from the palette).
        public static GolfMapBiomeAsset Asset(GolfMapJsonObject m)
        {
            var id = m.String("id");
            string renderer, label; Parse(id, out renderer, out label);
            var unity = m.Object("unity");
            var unityGuid = unity == null ? null : unity.String("guid");
            return new GolfMapBiomeAsset
            {
                model = id, renderer = renderer, fromLibrary = true,
                guid = string.IsNullOrEmpty(unityGuid) ? null : unityGuid, name = label,
                path = unity == null ? null : unity.String("path"), assetType = unity == null ? null : unity.String("assetType"),
                catalogueGuid = unity == null ? null : unity.String("catalogueGuid"),
                species = m.String("species"), kind = m.String("kind"), form = m.String("form"),
                heightM = m.Number("heightM"), crownWidthM = m.Number("crownWidthM"),
            };
        }

        // The golf-map repo (its scripts/models.ts runs every change to models.json and palette.json). An older
        // setup only named the repo's data/arborist/catalog-sizes.json: the repo is then the folder above data/.
        public const string RepoPref = "GolfMap.RepoRoot";
        const string OldCataloguePref = "GolfMap.ArboristCatalogueSizes";

        public static string RepoRoot()
        {
            var repo = EditorPrefs.GetString(RepoPref, "");
            if (string.IsNullOrEmpty(repo))
            {
                var catalogue = EditorPrefs.GetString(OldCataloguePref, "");
                if (!string.IsNullOrEmpty(catalogue)) repo = Path.GetDirectoryName(Path.GetDirectoryName(Path.GetDirectoryName(catalogue)));
            }
            if (string.IsNullOrEmpty(repo) || !File.Exists(Path.Combine(repo, "scripts/models.ts"))) repo = SyncedFrom() ?? repo;
            return !string.IsNullOrEmpty(repo) && File.Exists(Path.Combine(repo, "scripts/models.ts")) ? repo.Replace('\\', '/') : null;
        }

        // The repo the scripts were last pushed from (unity/mcp/sync.ts records it in Library/GolfMapBridge/sync-state.json).
        static string SyncedFrom()
        {
            try
            {
                var state = Path.Combine(Path.GetDirectoryName(UnityEngine.Application.dataPath), "Library/GolfMapBridge/sync-state.json");
                return File.Exists(state) ? GolfMapJsonDoc.ParseObject(File.ReadAllText(state)).String("repo") : null;
            }
            catch (Exception) { return null; }
        }

        // bun: GOLFMAP_BUN, else the user's ~/.bun/bin/bun.exe, else whatever PATH finds.
        static string Bun()
        {
            var env = Environment.GetEnvironmentVariable("GOLFMAP_BUN");
            if (!string.IsNullOrEmpty(env)) return env;
            var home = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".bun/bin/bun.exe");
            return File.Exists(home) ? home : "bun";
        }

        // One argument for the Windows command line: inner quotes escaped, a trailing backslash doubled.
        static string Quote(string arg)
        {
            arg = (arg ?? "").Replace("\"", "\\\"");
            return "\"" + (arg.EndsWith("\\") ? arg + "\\" : arg) + "\"";
        }

        // `bun run models -- <args>` in the repo, exactly as on the command line; throws its output on failure.
        public static string RunCli(string repo, params string[] args)
        {
            if (string.IsNullOrEmpty(repo)) throw new Exception("Pick the golf-map repo first: its bun run models writes models.json and palette.json.");
            var psi = new System.Diagnostics.ProcessStartInfo(Bun(), "run models -- " + string.Join(" ", args.Select(Quote).ToArray()))
            {
                WorkingDirectory = repo, UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true,
            };
            var log = new StringBuilder();
            using (var p = new System.Diagnostics.Process { StartInfo = psi })
            {
                p.OutputDataReceived += (o, e) => { if (e.Data != null) lock (log) log.AppendLine(e.Data); };
                p.ErrorDataReceived += (o, e) => { if (e.Data != null) lock (log) log.AppendLine(e.Data); };
                try { p.Start(); }
                catch (Exception e) { throw new Exception("Cannot run bun (" + psi.FileName + "): " + e.Message + ". Set GOLFMAP_BUN to bun.exe."); }
                p.BeginOutputReadLine();
                p.BeginErrorReadLine();
                if (!p.WaitForExit(120 * 1000)) { try { p.Kill(); } catch { } throw new Exception("bun run models took over 2 minutes."); }
                p.WaitForExit();
                var output = log.ToString().Trim();
                if (p.ExitCode != 0) throw new Exception("bun run models -- " + args[0] + " failed (exit " + p.ExitCode + "):\n" + output);
                return output;
            }
        }

        // The course folder of a palette (where the sync writes models.json and palette.json), absolute.
        public static string UnityFolderOf(string palettePath) { return Path.GetFullPath(Path.GetDirectoryName(palettePath)).Replace('\\', '/'); }

        // An Arborist model for the palette: one the course's library already has (the shared library's included)
        // as it is, else added to the course's models.json in the repo (`bun run models -- add`: sized from
        // Arborist's catalogue, refused for a label Arborist lacks) and synced into the course folder beside
        // `palettePath`. Returns it as the matcher's asset, read back from the synced copy.
        public static GolfMapBiomeAsset AddArborist(string repo, string course, string palettePath, string label, string species, string kind, string form)
        {
            var id = Id(Arborist, (label ?? "").Trim());
            GolfMapJsonObject model;
            if (Load(PathBeside(palettePath)).TryGetValue(id, out model)) return Asset(model);
            RunCli(repo, "add", course, id, "--species", species, "--kind", kind, "--form", form, "--unity", UnityFolderOf(palettePath));
            if (!Load(PathBeside(palettePath)).TryGetValue(id, out model)) throw new Exception(id + " was added to the repo's models.json but is not in " + PathBeside(palettePath) + " (the sync did not run?).");
            return Asset(model);
        }

        // The palette as `text` becomes the repo's palette.json (`bun run models -- palette`: checked against the
        // library) and is synced over `palettePath`, which this text was edited from (--replace-unity).
        public static string SavePalette(string repo, string course, string palettePath, string text)
        {
            var temp = Path.Combine(Path.GetTempPath(), "golfmap-palette-" + Guid.NewGuid().ToString("N") + ".json");
            File.WriteAllText(temp, text);
            try { return RunCli(repo, "palette", course, "--from", temp, "--replace-unity", "--unity", UnityFolderOf(palettePath)); }
            finally { try { File.Delete(temp); } catch { } }
        }
    }
}
