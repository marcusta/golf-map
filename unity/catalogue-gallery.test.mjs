// DOM-only regression check. No browser or external resources are loaded.
import {Window} from '../web/node_modules/happy-dom/lib/index.js';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const root=process.argv[2];
if(!root)throw Error('Provide catalogue directory');
const html=fs.readFileSync(root+'/index.html','utf8');
const window=new Window({url:'https://catalogue.invalid/index.html',settings:{disableCSSFileLoading:true,disableJavaScriptFileLoading:true,disableJavaScriptEvaluation:true}});
window.document.write(html);
const scripts=[...window.document.querySelectorAll('script')];
window.eval(scripts.find(s=>!s.type).textContent);
const doc=window.document;
assert.equal(doc.querySelectorAll('article').length,24);
assert.match(doc.getElementById('page').textContent,/Page 1 of 59/);
const first=doc.querySelector('article h2').textContent;
doc.getElementById('next').click();
assert.match(doc.getElementById('page').textContent,/Page 2 of 59/);
assert.notEqual(doc.querySelector('article h2').textContent,first);
const search=doc.getElementById('search');
search.value='Birch';search.dispatchEvent(new window.Event('input'));
await new Promise(resolve=>setTimeout(resolve,180));
assert.ok(doc.querySelectorAll('article').length>0);
assert.ok([...doc.querySelectorAll('article')].every(a=>a.textContent.toLowerCase().includes('birch')));
assert.ok(doc.querySelectorAll('article').length<=24);
const detail=doc.querySelector('article a').getAttribute('href');
assert.ok(fs.existsSync(root+'/'+detail));
search.value='NO_SUCH_ASSET_234234';search.dispatchEvent(new window.Event('input'));
await new Promise(resolve=>setTimeout(resolve,180));
assert.equal(doc.querySelectorAll('article').length,0);
assert.equal(doc.getElementById('empty').hidden,false);
assert.equal(doc.getElementById('next').disabled,true);
await window.happyDOM.close();
console.log('PASS: 24-card limit, pagination, filtering, empty state and metadata link');
