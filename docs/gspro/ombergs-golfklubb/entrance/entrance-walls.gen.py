"""Omberg's car entrance: two dry-laid granite walls with a pillar and a black post-top lantern each, the north one carrying
the sign ("Ombergs Golf", "VÄLKOMMEN", the INSEKTSHOTELL arrow plate) in raised white letters (props_kit `entrance_wall`).
Writes entrance-walls.json (props spec).

    python docs/gspro/ombergs-golfklubb/entrance/entrance-walls.gen.py
    blender -b --factory-startup --python blender/tools/build_props.py -- --spec docs/gspro/ombergs-golfklubb/entrance/entrance-walls.json --out data/omberg-entrance-walls/build --preview
    pwsh docs/gspro/ombergs-golfklubb/clubhouse/install.ps1 -Build data/omberg-entrance-walls/build -UnityProject D:/gspro_courses/omberg_v4_2025_12_02 -CourseFolder Omberg
    then golfmap.props.place only=omberg_entrance_wall_n,omberg_entrance_wall_s save=true in Unity.

Evidence: Marcus's Street View photo looking in along the entrance road (entrance-walls-ref.webp), the 2025 ortho and the 2022
lidar (entrance-walls-ortho.png / -lidar.png, SWEREF99 TM; lidar ends +-0.5 m, so the ends are the ortho's). Each wall stands
almost across the road (wall bearing ~30 deg, road ~120 deg); the pillar is at the road end. The north wall's top falls from
1.3 m to 1.1 m toward the far end (lidar 1.5 / 1.3 / 1.3 / 1.1 above the ground); the south wall is level. e/n = the wall's
middle, yawDeg = the bearing from the pillar to the far end, `face` = the side (local y) that looks at the road.
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

BOLD = "C:/Windows/Fonts/segoeuib.ttf"

# Per wall: pillar centre and far end (E, N); `ground` = the course MESH's height (m) at the pillar and at the far end and `y0`
# = the height Unity puts the asset's origin at (props.place's median of the footprint + dz), measured 2026-10-19 with
# golfmap.terrain.conform dryRun + props.place dryRun - the wall tops are given above the local ground and turned into
# heights over y0 here. Re-measure (and re-run) after a terrain / mesh change under the walls.
WALLS = {
    "omberg_entrance_wall_n": dict(
        p=(478012.6, 6457734.7), f=(478015.5, 6457739.7), face=-1, seed=7, dz=-0.10, y0=28.9708, ground=(29.208, 28.852),
        wallH=(1.30, 1.33), pillarH=1.5,   # the top falls ~0.3 m toward the far end (photo: nearly level), the ground ~0.36 m
        sign=dict(lines=[dict(text="Ombergs Golf", width=2.7, x=1.95, dz=0.30, depth=0.03, font=BOLD),
                         dict(text="VÄLKOMMEN", width=1.6, x=1.87, dz=0.78, depth=0.025)],
                  plate=dict(x=4.48, dz=0.30, w=1.1, h=0.30, text="INSEKTSHOTELL"))),
    "omberg_entrance_wall_s": dict(
        p=(478009.4, 6457729.7), f=(478006.5, 6457724.8), face=1, seed=19, dz=0.0, y0=28.8579, ground=(29.185, 28.866),
        wallH=(1.5, 1.5), pillarH=1.65),   # level 1.5 m over the ground: the top falls with it (~0.32 m), as in the photo
}
PILLAR = 0.72


def spec():
    assets, instances = {}, []
    for name, w in WALLS.items():
        dE, dN = w["f"][0] - w["p"][0], w["f"][1] - w["p"][1]
        length = math.hypot(dE, dN)
        gp, gf = w["ground"]
        gw = gp + (gf - gp) * (PILLAR / 2) / length  # the ground at the wall's start, beside the pillar
        hTop = [round(gw + w["wallH"][0] - w["y0"], 3), round(gf + w["wallH"][1] - w["y0"], 3)]
        yaw = math.degrees(math.atan2(dE, dN)) % 360.0
        part = {"kind": "entrance_wall", "length": round(length, 2), "thick": 0.55, "hTop": hTop,
                "pillar": {"size": PILLAR, "height": round(gp + w["pillarH"] - w["y0"], 3), "lantern": 0.75}, "face": w["face"], "seed": w["seed"],
                "depth": 0.6, "stone": 0.3, "batter": 0.07, "darkness": 0.88, "tint": [0.97, 0.96, 0.96], "colorKey": name.replace("omberg_entrance_wall_", "")}
        part.update({k: w[k] for k in ("darkness", "tint", "batter") if k in w})
        if "sign" in w:
            part["sign"] = w["sign"]
        assets[name] = {"category": "structure", "collider": "mesh", "bake": True, "parts": [part]}
        instances.append({"asset": name, "e": round((w["p"][0] + w["f"][0]) / 2, 2), "n": round((w["p"][1] + w["f"][1]) / 2, 2),
                          "yawDeg": round(yaw, 1), "ground": "median", "dz": w["dz"]})
    return {"format": "golfmap-props-spec-v1", "course": "ombergs-golfklubb", "origin": [478010.0, 6457732.0],
            "note": "Omberg's car entrance walls, generated by entrance-walls.gen.py", "assets": assets, "instances": instances}


if __name__ == "__main__":
    out = os.path.join(HERE, "entrance-walls.json")
    sp = spec()
    json.dump(sp, open(out, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print("wrote", out, list(sp["assets"]), [(i["asset"], i["e"], i["n"], i["yawDeg"]) for i in sp["instances"]])
