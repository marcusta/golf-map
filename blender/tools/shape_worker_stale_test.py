"""Is the conformed cache stale? The three inputs, checked with files only - no course, no OPCD, no worker.

`shape_worker.conformed_stale` decides whether /load has to run shape_prepare again. terrain.obj is
rewritten from every DEM export, so its mtime moves on its own: the check must compare the OBJ's content
against the sha shape_prepare recorded next to the conformed .blend, not the mtimes.

Run from the repository root:
    "C:/Program Files/Blender Foundation/Blender 4.5/blender.exe" -b --factory-startup --python-exit-code 1 --python blender/tools/shape_worker_stale_test.py
"""
import json
import os
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shape_prepare as sp  # noqa: E402
import shape_worker as sw  # noqa: E402

FAILED = []
NOW = time.time()


def check(what, got, want):
    ok = got == want
    print(("  ok   " if ok else "  FAIL ") + what + ("" if ok else f"  got {got!r}, want {want!r}"))
    if not ok:
        FAILED.append(what)


def touch(path, text, age):
    """Write `path` and set its mtime `age` seconds into the past (explicitly, so two writes in the same
    millisecond are still different files to a mtime check)."""
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    os.utime(path, (NOW - age, NOW - age))
    return path


def record_sha(conformed, source, terrain):
    """What shape_prepare leaves next to the conformed .blend after a run."""
    sha, _ = sp.terrain_fingerprint(terrain, sp.cache_dir_for(source))
    sp.write_terrain_sidecar(conformed, source, terrain, sha, {"Terrain": "t" * 40, "Outer": None})
    return sha


with tempfile.TemporaryDirectory(prefix="golfmap_stale_") as folder:
    source = os.path.join(folder, "course.blend")
    conformed = os.path.join(folder, "course.conformed.blend")
    report = os.path.splitext(conformed)[0] + ".json"
    terrain = os.path.join(folder, "terrain.obj")
    TERRAIN_A = "v 1.0 2.0 3.0\n"
    TERRAIN_B = "v 9.5 9.5 9.5\nv 9.5 9.5 9.6\n"   # another DEM: other bytes, other size

    # The usual state: a course, its terrain, a conformed cache newer than both, and the sidecar
    # shape_prepare writes with the terrain's content sha.
    touch(source, "source", 600)
    touch(terrain, TERRAIN_A, 600)
    touch(conformed, "conformed", 300)
    sha_a = record_sha(conformed, source, terrain)

    check("everything current -> not stale", sw.conformed_stale(source, conformed), (False, ""))
    check("the sidecar is where the worker looks",
          os.path.basename(sp.terrain_sidecar_path(conformed)), "course.conformed.terrain.json")

    # A terrain.obj rewritten from the same heightmap: new mtime, same bytes. A mtime check would make
    # this a 2.5-minute conform for nothing; the sha keeps the cache.
    touch(terrain, TERRAIN_A, 0)
    check("terrain.obj rewritten with the same bytes -> not stale",
          sw.conformed_stale(source, conformed), (False, ""))

    # A terrain.obj regenerated from a new DEM: the content differs, so the cache is stale. This is the
    # case the old check missed entirely - it never looked at terrain.obj at all.
    touch(terrain, TERRAIN_B, 0)
    stale, why = sw.conformed_stale(source, conformed)
    check("terrain.obj with new content -> stale", stale, True)
    check("  and says which sha it expected", ("terrain.obj changed" in why, sha_a[:12] in why), (True, True))

    # No sha recorded (a conformed .blend from before the sidecar): fall back to the mtimes.
    os.remove(sp.terrain_sidecar_path(conformed))
    stale, why = sw.conformed_stale(source, conformed)
    check("no sha anywhere, terrain.obj newer than the cache -> stale",
          (stale, "no terrain sha was recorded" in why), (True, True))
    touch(terrain, TERRAIN_B, 900)
    check("no sha anywhere, terrain.obj older than the cache -> not stale",
          sw.conformed_stale(source, conformed), (False, ""))

    # The prepare report the worker writes next to the cache carries the sha too, so a lost sidecar
    # still gets a content comparison.
    with open(report, "w", encoding="utf-8") as f:
        json.dump({"format": sp.FORMAT, "terrainSha": "0" * 40}, f)
    stale, why = sw.conformed_stale(source, conformed)
    check("the report's sha is used when the sidecar is gone",
          (stale, "terrain.obj changed" in why), (True, True))
    os.remove(report)

    # The source .blend regenerated by OPCD (which also rebuilds the Outer terrain inside it, so the
    # source's mtime is what covers Outer).
    record_sha(conformed, source, terrain)
    check("a current source -> not stale", sw.conformed_stale(source, conformed), (False, ""))
    touch(source, "regenerated", 0)
    stale, why = sw.conformed_stale(source, conformed)
    check("a newer source .blend -> stale", (stale, "is newer than" in why), (True, True))
    touch(source, "source", 600)

    # No conformed cache at all, and a missing terrain.obj (prepare would fail on that; not this check's
    # call to make).
    os.remove(conformed)
    check("no conformed cache -> stale", sw.conformed_stale(source, conformed)[0], True)
    touch(conformed, "conformed", 300)
    os.remove(terrain)
    check("no terrain.obj -> not stale on that account",
          sw.conformed_stale(source, conformed), (False, ""))

print(("FAILED: " + ", ".join(FAILED)) if FAILED else "all conformed_stale checks passed")
sys.exit(1 if FAILED else 0)
