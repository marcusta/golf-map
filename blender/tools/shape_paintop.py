"""golfmap.paint: rule-based vertex paint of the course meshes as a shaping op (the bpy side of shape_paintrules).

One op = one paint.json rule or stroke, generated by `pipeline/gspro.py shaping-paint` into
`docs/gspro/<course>/shaping/90-paint.gen.json` in Unity's order (object -> road -> edge, then the lake bed, then the
strokes):

    {"id": "paint-ram-roads", "op": "golfmap.paint",
     "rule": {"id": "ram-roads", "kind": "road", "surfaces": ["Rough", "Deep"], "channel": "black", ...},
     "source": "<optional: the export file to read instead of the course's own, relative to the course folder>"}

Units: one per course mesh the rule can paint (Spline_* only: never a water plane, a R.A.M. road or any other
object), id = the mesh's name. Reads = that mesh (plus, for an edge rule, the bunker blends within widthM of it, whose
border it reads); writes = the meshes whose colours changed. A rule that reads an export file (road: the R.A.M.
roads, object with `creek`: the creeks, lakebed: the lake plane) reads it at replay time and keys its units on the
file's content sha (`extra`), so an edited export re-runs it; shape_paintrules.dependency gives the worker the same sha
for its op diff. Colours: the `Col` corner attribute, as sRGB bytes (Unity's vertex colours), alpha kept.

shape_apply registers it (RUNNERS / PLANNERS through thin wrappers, so the worker's reload of this module takes
effect); shape_layers.OPS takes OP_SPEC. Never imports shape_apply (the op cache would key the whole file).
"""

import json
import os
import time

import bpy
import numpy as np

import shape_paintrules as pr

KIND = "golfmap.paint"
# shape_layers.OPS["golfmap.paint"]
OP_SPEC = {"params": {}, "keys": {"rule", "source"}, "required": {"rule"}, "noSelect": True}

_FILES = {}   # (path, what) -> ((size, mtime), sha, parsed): the export files, read again when they change


class PaintUnit:
    """A paint unit, shaped like shape_apply.Unit (the unit runner's duck type): one course mesh."""

    def __init__(self, uid, targets, reads=(), extra=""):
        self.id = uid
        self.targets = list(targets)
        self.seed = None
        self._reads = set(reads)
        self.extra = extra
        self.current = None
        self.region = None
        self.cut_paint = None

    def reads(self, margin=0.0):
        return set(self._reads) | set(self.targets)


def course_folder(ctx):
    """The course export folder (the .blend's, holding the inner DEM sidecar and the exports)."""
    sidecar = getattr(ctx, "dem_sidecar", None)
    return os.path.dirname(sidecar) if sidecar else os.path.dirname(bpy.data.filepath)


def dependency(op, folder):
    """For the worker's op diff: the op's export file and its sha (None: reads no file)."""
    return pr.dependency(op, folder)


def _course_meshes():
    return [o for o in bpy.data.objects if o.type == "MESH" and pr.is_course_mesh(o.name)]


def _world(obj):
    me = obj.data
    co = np.empty(len(me.vertices) * 3, dtype=np.float32)
    me.vertices.foreach_get("co", co)
    m = np.array(obj.matrix_world, dtype=np.float64)
    return co.reshape(-1, 3).astype(np.float64) @ m[:3, :3].T + m[:3, 3]


def _box3(obj):
    w = _world(obj)
    return (w.min(axis=0), w.max(axis=0)) if len(w) else None


def _box_xy(ctx, obj):
    """XY box in the .blend world: ctx.box (cached, local positions) when the object is not transformed."""
    if obj.matrix_world.is_identity and hasattr(ctx, "box"):
        return ctx.box(obj.name)
    b = _box3(obj)
    return None if b is None else (float(b[0][0]), float(b[0][1]), float(b[1][0]), float(b[1][1]))


def _box_gap(a, b):
    return max(a[0] - b[2], b[0] - a[2], a[1] - b[3], b[1] - a[3], 0.0)


def _corners(me):
    n = len(me.loops)
    lv = np.empty(n, dtype=np.int64)
    me.loops.foreach_get("vertex_index", lv)
    ls = np.empty(len(me.polygons), dtype=np.int64)
    lt = np.empty(len(me.polygons), dtype=np.int64)
    me.polygons.foreach_get("loop_start", ls)
    me.polygons.foreach_get("loop_total", lt)
    return lv, ls, lt


def border(obj):
    """World positions of the mesh's border vertices (shape_paintrules.boundary_points: welded to a millimetre)."""
    lv, ls, lt = _corners(obj.data)
    return pr.boundary_points(_world(obj), lv, ls, lt)


def _load(path, what, arg=None):
    """(sha, parsed) of an export file, memoised while its size and mtime hold."""
    st = os.stat(path)
    stamp = (st.st_size, st.st_mtime_ns)
    key = (path, what, arg)
    hit = _FILES.get(key)
    if hit is not None and hit[0] == stamp:
        return hit[1], hit[2]
    sha = pr.file_sha(path)
    if what == "road":
        parsed = pr.road_samples(pr.load_roads(path))
    elif what == "creek":
        parsed = pr.load_creek(path, arg)
    else:
        parsed = pr.load_lake_plane(path)
    _FILES[key] = (stamp, sha, parsed)
    return sha, parsed


def _input(ctx, op, rule):
    """(path, sha, parsed, problem) of the rule's export file; (None, None, None, None) for a rule that reads none."""
    path = pr.rule_file(rule, course_folder(ctx), op.get("source"))
    what = "creek" if rule["kind"] == "object" and rule.get("creek") else rule["kind"]
    if what not in ("road", "creek", "lakebed"):
        return None, None, None, None
    if path is None or not os.path.isfile(path):
        return path, None, None, f"{op['id']}: no {pr.FILE_SUFFIX[what]} export ({path or 'no course prefix'}): nothing painted"
    sha, parsed = _load(path, what, rule.get("creek") if what == "creek" else None)
    if what == "creek" and parsed is None:
        return path, sha, None, f"{op['id']}: creek {rule['creek']} is not in {os.path.basename(path)} (export creeks first)"
    return path, sha, parsed, None


def plan_paint(ctx, op):
    """The op's units (one per course mesh it can paint) and its problems (a missing export file or creek)."""
    rule = pr.normalise(op["rule"], op["id"])
    path, sha, parsed, problem = _input(ctx, op, rule)
    if problem:
        return [], [problem]
    extra = json.dumps([os.path.basename(path), sha]) if path else ""
    kind = rule["kind"]
    meshes = _course_meshes()
    units = []
    if kind == "object":
        units = [PaintUnit(o.name, [o.name], extra=extra) for o in meshes if rule["match"] in o.name]
    elif kind == "road":
        samples = parsed
        reach = pr.road_reach(samples, rule)
        for o in meshes:
            if pr.classify(o.name) not in rule["surfaces"] or not len(samples):
                continue
            b = _box_xy(ctx, o)
            if b and ((samples[:, 0] >= b[0] - reach) & (samples[:, 0] <= b[2] + reach)
                      & (samples[:, 1] >= b[1] - reach) & (samples[:, 1] <= b[3] + reach)).any():
                units.append(PaintUnit(o.name, [o.name], extra=extra))
    elif kind == "edge":
        blends = [(o.name, _box_xy(ctx, o)) for o in meshes if pr.BUNKER_BLEND in o.name]
        for o in meshes:
            if pr.classify(o.name) not in rule["surfaces"]:
                continue
            b = _box_xy(ctx, o)
            near = sorted(n for n, bb in blends if b and bb and _box_gap(b, bb) <= rule["widthM"])
            if near:
                units.append(PaintUnit(o.name, [o.name], near, extra=extra))
    elif kind == "lakebed":
        for o in meshes:
            if o.name.endswith(rule["match"]):
                b = _box3(o)
                if b is not None and pr.lake_mesh_selected(o.name, b[0], b[1], parsed, rule["match"]):
                    units.append(PaintUnit(o.name, [o.name], extra=extra))
    else:
        box = pr.stroke_box(pr.stroke_geometry(rule, ctx.frame), rule)
        for o in meshes:
            if pr.stroke_touches(o.name, rule):
                b = _box_xy(ctx, o)
                if b and _box_gap(b, box) <= 0.0:
                    units.append(PaintUnit(o.name, [o.name], extra=extra))
    units.sort(key=lambda u: u.id)
    return units, []


def _colours(me, default):
    """(attribute or None, colours (K, 4) float64 per corner or point, domain, foreach key) of `Col`."""
    attr = me.color_attributes.get("Col")
    if attr is None:
        return None, np.tile(np.array(default, dtype=np.float64), (len(me.loops), 1)), "CORNER", "color_srgb"
    key = "color_srgb" if attr.data_type == "BYTE_COLOR" else "color"
    buf = np.empty(len(attr.data) * 4, dtype=np.float32)
    attr.data.foreach_get(key, buf)
    return attr, buf.reshape(-1, 4).astype(np.float64), attr.domain, key


def _bytes(c):
    return np.floor(np.clip(c, 0.0, 1.0) * 255.0 + 0.5)


def weights(ctx, rule, obj, world, parsed, unit):
    """Per vertex paint weight of the rule on this mesh."""
    kind = rule["kind"]
    if kind == "object":
        line, left, right = parsed if parsed is not None else (None, float("nan"), float("nan"))
        return pr.object_weights(world, border(obj), rule, line, left, right)
    if kind == "road":
        return pr.road_weights(world[:, :2], parsed, rule)
    if kind == "edge":
        pts = [border(bpy.data.objects[n]) for n in sorted(unit.reads()) if n != obj.name and n in bpy.data.objects]
        return pr.edge_weights(world[:, :2], np.concatenate(pts) if pts else np.zeros((0, 3)), rule)
    if kind == "lakebed":
        return pr.lakebed_weights(world, parsed, rule)
    return pr.stroke_weights(world[:, :2], pr.stroke_geometry(rule, ctx.frame), rule)


def paint_unit(ctx, op, rule, unit):
    """Paint one mesh: its `Col` colours lerped (or raised) toward the rule's channel by the rule's weight."""
    t = time.time()
    run = {"feature": unit.id, "targets": list(unit.targets), "seed": None, "rule": rule["id"], "kind": rule["kind"]}
    obj = bpy.data.objects.get(unit.id)
    if obj is None or obj.type != "MESH":
        return dict(run, result=["CANCELLED"], error=f"{unit.id} does not exist")
    _, _, parsed, problem = _input(ctx, op, rule)
    if problem:
        return dict(run, result=["CANCELLED"], error=problem)
    me = obj.data
    world = _world(obj)
    lake = rule["kind"] == "lakebed"
    attr, old, domain, key = _colours(me, pr.LAKE_DEFAULT_COLOUR if lake else pr.DEFAULT_COLOUR)
    w = weights(ctx, rule, obj, world, parsed, unit)
    lv = _corners(me)[0]
    per = w[lv] if domain == "CORNER" else w
    new = pr.apply_channel(old, per, rule["channel"], rule.get("mode", "replace"), 0.0 if lake else pr.MIN_WEIGHT)
    changed = (_bytes(new) != _bytes(old)).any(axis=1) if key == "color_srgb" else (new != old).any(axis=1)
    if changed.any() or (attr is None and (w > 0).any()):
        if attr is None:
            attr = me.color_attributes.new("Col", "BYTE_COLOR", "CORNER")
            me.color_attributes.active_color = attr
            me.color_attributes.render_color_index = me.color_attributes.find("Col")
        attr.data.foreach_set(key, new.astype(np.float32).ravel())
        me.update()
    verts = np.unique(lv[changed]) if domain == "CORNER" else np.nonzero(changed)[0]
    run.update(result=["FINISHED"], vertices=len(world), painted=int(len(verts)), seconds=round(time.time() - t, 3))
    return run


def op_paint(ctx, op):
    """Runner of golfmap.paint: every unit through the unit runner (op cache, footprints)."""
    units, problems = plan_paint(ctx, op)
    rule = pr.normalise(op["rule"], op["id"])
    runs = []
    for unit in units:
        run = ctx.runner.run(ctx, op, unit, (lambda unit=unit: paint_unit(ctx, op, rule, unit)))
        if run is not None:
            runs.append(run)
    painted = sum(1 for r in runs if r.get("painted"))
    print(f"[shape_apply] paint {op['id']} ({rule['kind']}): {len(units)} mesh(es) in reach, {painted} painted")
    return runs, problems
